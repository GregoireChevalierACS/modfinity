/** A message waiting in the mod's inbox, shown in game as the event promptitude_inbox.1. */
export interface InboxMessage {
  readonly id: number;
  readonly title: string;
  readonly text: string;
}

export interface InboxFile {
  /** Path relative to the mod root. */
  readonly relativePath: string;
  readonly content: string;
}

const LANGUAGES = ['english', 'french'] as const;
const OK_LABEL: Readonly<Record<(typeof LANGUAGES)[number], string>> = { english: 'Understood.', french: 'Compris.' };
const TITLE_QUESTION_LENGTH = 48;
/** Message ids are compared as game variables: keep them well within their range. */
const ID_EPOCH = Date.UTC(2026, 0, 1);

/**
 * Ids must always grow, even across companion restarts, because the game remembers the last
 * message read. Minutes elapsed since 2026 give a growing floor without storing anything.
 */
export function nextMessageId(previousId: number | null, now: Date): number {
  const floor = Math.floor((now.getTime() - ID_EPOCH) / 60_000);
  return Math.max(floor, (previousId ?? 0) + 1);
}

export function messageTitle(question: string): string {
  const short =
    question.length <= TITLE_QUESTION_LENGTH ? question : `${question.slice(0, TITLE_QUESTION_LENGTH - 1).trimEnd()}…`;
  return `Promptitude : ${short}`;
}

/** Files that replace the inbox of the mod; the game reloads them while it runs. */
export function renderInbox(message: InboxMessage): InboxFile[] {
  return [
    {
      relativePath: 'in_game/common/scripted_triggers/promptitude_inbox_triggers.txt',
      content: `# GENERATED by the Promptitude companion: overwritten for each message.
# Message ${message.id}.
promptitude_inbox_has_message = {
	promptitude_is_unread_message = { ID = ${message.id} }
}
`,
    },
    {
      relativePath: 'in_game/common/scripted_effects/promptitude_inbox_effects.txt',
      content: `# GENERATED by the Promptitude companion: overwritten for each message.
# Message ${message.id}.
promptitude_inbox_apply_effect = {
	promptitude_mark_message_read_effect = { ID = ${message.id} }
}
`,
    },
    ...LANGUAGES.map((language) => ({
      relativePath: `main_menu/localization/${language}/promptitude_inbox_l_${language}.yml`,
      content: `l_${language}:
 promptitude_inbox.title: "${escapeLocalization(message.title)}"
 promptitude_inbox.desc: "${escapeLocalization(message.text)}"
 promptitude_inbox.ok: "${OK_LABEL[language]}"
`,
    })),
  ];
}

/** Localization values sit between double quotes on a single line. */
export function escapeLocalization(value: string): string {
  return value.replaceAll('\\', '\\\\').replaceAll('"', '\\"').replace(/\r?\n/g, '\\n');
}
